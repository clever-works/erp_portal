/** Builds a simple one-page PDF for a document row and starts the download. */
export function downloadDocumentPdf(columns: string[], row: string[]) {
  const pdf = new SimplePdf();
  const W = pdf.width; const M = 48;
  const get = (col: string) => row[columns.indexOf(col)] ?? "";
  const title = get("Document").replace(/\.[a-z0-9]+$/i, "");

  pdf.rect(0, 0, W, 84, "#003443").rect(0, 80, W, 4, "#00afb9");
  pdf.text(M, 40, title, { size: 20, bold: true, color: "#ffffff" });
  pdf.text(M, 62, company.name, { size: 10, color: "#bbefff" });

  let y = 118;
  const meta: [string, string][] = [["Category", get("Category")], ["Owner", get("Owner")], ["Last updated", get("Last updated")], ["Access", get("Access")]];
  meta.forEach(([k, v], i) => { pdf.text(M + (i % 2) * 250, y + Math.floor(i / 2) * 18, `${k}:`, { size: 9.5, color: "#4a6a75" }); pdf.text(M + 80 + (i % 2) * 250, y + Math.floor(i / 2) * 18, v, { size: 9.5, bold: true, color: "#001a22" }); });
  y += 52;
  pdf.line(M, y, W - M, y, "#dbe5e3");
  y += 28;

  for (const [heading, lines] of bodies[title] ?? [["About this document", [`This is the ${title} shared in the Nexus ERP portal.`, "Contact the owner listed above for the latest version."]]]) {
    pdf.text(M, y, heading, { size: 13, bold: true, color: "#00696e" });
    y += 20;
    for (const line of lines) { pdf.text(M + 10, y, `- ${line}`, { size: 10.5, color: "#001a22" }); y += 16; }
    y += 12;
  }

  pdf.line(M, 790, W - M, 790, "#dbe5e3");
  pdf.text(M, 806, `${company.name}  |  Internal document  |  Demo copy generated by Nexus ERP`, { size: 8.5, color: "#4a6a75" });

  const url = URL.createObjectURL(pdf.toBlob());
  const a = document.createElement("a"); a.href = url; a.download = `${fileSlug(title)}.pdf`; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
